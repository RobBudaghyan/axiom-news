// Writes public/app/i18n.js (Step 9: the Mini App's strings, generated from config/i18n/<lang>.json
// and config/languages.json, so the dictionaries stay one file per language) and a short content
// hash into public/app/index.html for app.css, i18n.js and app.js (?v=<hash>), so Telegram's
// WebView never shows stale files after a deploy (lesson 12). Runs before every deploy
// (npm run deploy); test/app.test.mjs fails if either is out of date.
//   node scripts/stamp-app.mjs          update i18n.js and the stamps
//   node scripts/stamp-app.mjs --check  exit 1 if they are out of date
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const DIR = fileURLToPath(new URL("../public/app/", import.meta.url));
const CONFIG = fileURLToPath(new URL("../../config/", import.meta.url));
const FILES = ["app.css", "i18n.js", "app.js"];
// The sections the Mini App uses. The Admin tab stays English (owner only) and is not in here.
const SECTIONS = ["app", "errors", "topics", "zones"];

export function i18nSource() {
  const langs = JSON.parse(readFileSync(`${CONFIG}languages.json`, "utf8"));
  const dicts = {};
  for (const code of langs.available) {
    const d = JSON.parse(readFileSync(`${CONFIG}i18n/${code}.json`, "utf8"));
    dicts[code] = Object.fromEntries(SECTIONS.filter((s) => d[s]).map((s) => [s, d[s]]));
  }
  const data = { enabled: langs.enabled, default: langs.default, names: langs.names, locale: langs.locale, dicts };
  return "// Generated by scripts/stamp-app.mjs from config/i18n/*.json and config/languages.json. Do not edit.\n" +
    `window.AXIOM_I18N = ${JSON.stringify(data)};\n`;
}

const hashText = (text) => createHash("sha256").update(text).digest("hex").slice(0, 10);
export const hashOf = (file) => hashText(file === "i18n.js" ? i18nSource() : readFileSync(DIR + file));

export function stamped() {
  let html = readFileSync(DIR + "index.html", "utf8");
  for (const f of FILES) {
    const at = html.indexOf(`${f}?v=`);
    if (at < 0) throw new Error(`index.html does not load ${f}?v=...`);
    const end = html.indexOf('"', at);
    html = `${html.slice(0, at)}${f}?v=${hashOf(f)}${html.slice(end)}`;
  }
  return html;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const current = readFileSync(DIR + "index.html", "utf8");
  let currentI18n = "";
  try { currentI18n = readFileSync(DIR + "i18n.js", "utf8"); } catch { /* first run */ }
  const nextI18n = i18nSource();
  if (process.argv.includes("--check")) {
    if (currentI18n !== nextI18n) { console.error("public/app/i18n.js is out of date: run node scripts/stamp-app.mjs"); process.exit(1); }
    if (current !== stamped()) { console.error("index.html stamps are out of date: run node scripts/stamp-app.mjs"); process.exit(1); }
    console.log("i18n.js and stamps up to date");
  } else {
    writeFileSync(DIR + "i18n.js", nextI18n);
    const next = stamped();
    writeFileSync(DIR + "index.html", next);
    console.log(current === next && currentI18n === nextI18n ? "already up to date" : "i18n.js and stamps updated");
  }
}
